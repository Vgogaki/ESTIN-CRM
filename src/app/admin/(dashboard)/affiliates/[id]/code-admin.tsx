"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/field";
import { Badge } from "@/components/ui/badge";

export type CodeRow = {
  id: string;
  code: string;
  origin: "generated" | "legacy_staff";
  createdAt: string;
  revokedAt: string | null;
  revokeReason: string | null;
};

const ORIGIN_TEXT = {
  generated: "Generated by the affiliate",
  legacy_staff: "Entered by staff (before codes were generated)",
} as const;

/** The register of this affiliate's codes: who made each one and when, and a way to deactivate the active one. */
export default function CodeAdmin({ codes }: { codes: CodeRow[] }) {
  const router = useRouter();
  const [reason, setReason] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const active = codes.find((c) => c.revokedAt === null);

  async function deactivate() {
    if (!active) return;
    setError(null);
    setBusy(true);
    try {
      const res = await fetch(`/api/admin/affiliates/codes/${active.id}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ reason }),
      });
      const data = await res.json();
      if (!res.ok) {
        setError(data.error ?? "Failed.");
        return;
      }
      setReason("");
      router.refresh();
    } finally {
      setBusy(false);
    }
  }

  return (
    <Card className="mb-5 p-5">
      <h2 className="mb-1 text-sm font-semibold">Referral codes</h2>
      <p className="mb-3 text-xs text-sub">
        Codes can only be generated by the affiliate, never typed by staff or by anyone else. A code that is not on this list earns nothing. Deactivated codes stay on record and are never reissued.
      </p>
      {codes.length === 0 ? (
        <p className="text-sm text-sub">No code generated yet. The affiliate generates it from their portal after signing in.</p>
      ) : (
        <div className="flex flex-col gap-2">
          {codes.map((c) => (
            <div key={c.id} className="flex items-start justify-between gap-3 text-sm">
              <div>
                <p>
                  <span className="font-mono font-semibold">{c.code}</span>
                </p>
                <p className="text-xs text-sub">
                  {ORIGIN_TEXT[c.origin]} · {new Date(c.createdAt).toLocaleString()}
                </p>
                {c.revokedAt && (
                  <p className="text-xs text-sub">
                    Deactivated {new Date(c.revokedAt).toLocaleString()}: {c.revokeReason}
                  </p>
                )}
              </div>
              <Badge tone={c.revokedAt ? "neutral" : "success"}>{c.revokedAt ? "deactivated" : "active"}</Badge>
            </div>
          ))}
        </div>
      )}
      {active && (
        <div className="mt-4 flex items-center gap-2">
          <Input value={reason} onChange={(e) => setReason(e.target.value)} placeholder="Reason for deactivating (required)" />
          <Button variant="danger" disabled={busy || reason.trim().length < 4} onClick={deactivate}>
            Deactivate code
          </Button>
        </div>
      )}
      {error && <p className="mt-2 text-xs text-danger">{error}</p>}
    </Card>
  );
}
